-- Domaine de revision d'un constat (banque, clients, fournisseurs, documents, TVA, stock, immobilisations, journal, comptabilite, cloture) :
-- derive du code du controle a la declaration, stocke pour filtrer et compter cote base. Les constats de reglement deja existants, dont le type de tiers
-- n'a pas ete enregistre, restent dans « OTHER » jusqu'a leur prochaine detection (qui met le domaine a jour).
ALTER TABLE finding ADD COLUMN domaine VARCHAR(30);

UPDATE finding SET domaine = CASE control_code
    WHEN 'UNMATCHED_PAYMENT' THEN 'BANK' WHEN 'AMBIGUOUS_BANK_MATCH' THEN 'BANK' WHEN 'MATCH_TO_CONFIRM' THEN 'BANK'
    WHEN 'BANK_DUPLICATE_TRANSACTION' THEN 'BANK' WHEN 'INTERNAL_TRANSFER_TO_CONFIRM' THEN 'BANK' WHEN 'INTERNAL_TRANSFER_AMBIGUOUS' THEN 'BANK'
    WHEN 'INTERNAL_TRANSFER_WITHOUT_ENTRY' THEN 'BANK'
    WHEN 'CLIENT_CREDIT_BALANCE' THEN 'CUSTOMER' WHEN 'SUPPLIER_DEBIT_BALANCE' THEN 'SUPPLIER'
    WHEN 'VAT_INCONSISTENCY' THEN 'VAT' WHEN 'TAX_DECLARATION_MISSING' THEN 'VAT' WHEN 'TAX_DECLARATION_LATE' THEN 'VAT'
    WHEN 'STOCK_INCONSISTENCY' THEN 'STOCK'
    WHEN 'FIXED_ASSET_WITHOUT_SOURCE' THEN 'FIXED_ASSET' WHEN 'POSSIBLE_DOUBLE_ACQUISITION' THEN 'FIXED_ASSET'
    WHEN 'ACCOUNT_NOT_CONFIGURED' THEN 'ACCOUNTING' WHEN 'ACCOUNT_AMBIGUOUS' THEN 'ACCOUNTING' WHEN 'ACCOUNT_INVALID' THEN 'ACCOUNTING'
    WHEN 'DRAFT_ENTRY_OLD' THEN 'JOURNAL' WHEN 'CLOSING_BLOCKER' THEN 'CLOSING'
    WHEN 'MISSING_DOCUMENT' THEN 'DOCUMENT' WHEN 'DUPLICATE_INVOICE' THEN 'DOCUMENT' WHEN 'DOCUMENT_AT_RISK' THEN 'DOCUMENT'
    WHEN 'EXACT_DUPLICATE' THEN 'DOCUMENT' WHEN 'POSSIBLE_DUPLICATE' THEN 'DOCUMENT'
    ELSE CASE WHEN control_code LIKE 'DOCUMENT\_%' THEN 'DOCUMENT' ELSE 'OTHER' END
END;

CREATE INDEX idx_finding_entreprise_domaine ON finding(entreprise_id, domaine, status);
